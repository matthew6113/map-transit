"""SFO AirTrain from Overture Maps (OpenStreetMap data), since no GTFS feed carries it.

Reads Overture's transportation segments in a box around SFO straight from S3 with pyarrow (anonymous,
as BAM's pipeline does), keeps the `monorail` class (the AirTrain is the only one there, named "SFO
AirTrain" on most pieces; the unnamed ones are its connectors and yard leads), and merges them into one
people-mover line. Its Red and Blue lines are service patterns on the same guideway, so one line.

Writes data/present/airtrain/{lines.json, segments.geojson, points.geojson} and this step's entries in
data/sources.json and data/systems.json. Stations: none yet (Overture's segments carry no stops).

    uv run --directory pipeline python -m transit_pipeline.overture
"""

from __future__ import annotations

import os

import pyarrow.compute as pc
import pyarrow.dataset as ds
import pyarrow.fs as pafs
import pyarrow.parquet as pq
import shapely
from shapely.ops import linemerge, unary_union

from .common import DATA, RAW, SOURCES, ensure_systems, merge_registry, round_coords, write_geojson, write_json

OVERTURE_RELEASE = "2026-09-23.1"  # the same release as BAM's basemap
BUCKET = "overturemaps-us-west-2"
SFO_BBOX = (-122.42, 37.60, -122.36, 37.645)
CACHE = RAW / "overture" / OVERTURE_RELEASE / "sfo-rail.parquet"
SOURCE_ID = "overture-transportation-2026-09-23-1"


def _filesystem() -> pafs.S3FileSystem:
    # Overture is a public bucket; injected placeholder AWS credentials make S3 refuse anonymous reads.
    for key in ("AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_SESSION_TOKEN"):
        os.environ.pop(key, None)
    return pafs.S3FileSystem(anonymous=True, region="us-west-2")


def fetch_segments():
    if CACHE.exists():
        return pq.read_table(CACHE)
    x0, y0, x1, y1 = SFO_BBOX
    dataset = ds.dataset(f"{BUCKET}/release/{OVERTURE_RELEASE}/theme=transportation/type=segment/",
                         filesystem=_filesystem(), format="parquet")
    filt = ((pc.field("bbox", "xmin") < x1) & (pc.field("bbox", "xmax") > x0)
            & (pc.field("bbox", "ymin") < y1) & (pc.field("bbox", "ymax") > y0) & (pc.field("subtype") == "rail"))
    table = dataset.to_table(columns=["id", "geometry", "class", "names", "rail_flags"], filter=filt)
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(table, CACHE, compression="zstd")
    return table


def main() -> None:
    rows = [r for r in fetch_segments().to_pylist() if r["class"] == "monorail"]
    if not rows:
        raise SystemExit("[overture] no monorail segments around SFO; check the release")
    named = sum(1 for r in rows if (r["names"] or {}).get("primary") == "SFO AirTrain")
    merged = linemerge(unary_union([shapely.from_wkb(r["geometry"]) for r in rows]))
    parts = [round_coords([list(c) for c in g.coords]) for g in getattr(merged, "geoms", [merged])]

    seg_id = "sfo-airtrain-guideway"
    method = (f"Overture Maps transportation segments, release {OVERTURE_RELEASE}: the {len(rows)} monorail-class "
              f"segments around SFO ({named} named 'SFO AirTrain'; the rest its connectors and yard leads), merged")
    segment = {
        "type": "Feature",
        "properties": {
            "id": seg_id,
            "system": "sfo-airtrain",
            "name": "SFO AirTrain guideway",
            "opened": None,
            "closed": None,
            "structure": "elevated",
            "geometry_confidence": "surveyed",
            "geometry_method": method,
            "sources": [{"source": SOURCE_ID, "supports": ["geometry"]}],
            "flags": ["opened_unsourced"],
        },
        "geometry": {"type": "LineString", "coordinates": parts[0]} if len(parts) == 1 else {"type": "MultiLineString", "coordinates": parts},
    }
    line = {
        "id": "sfo-airtrain",
        "name": "SFO AirTrain",
        "system": "sfo-airtrain",
        "operators": [{"name": "San Francisco International Airport"}],
        "mode": "people_mover",
        "era": "present",
        "opened": None,
        "closed": None,
        "status": "active",
        "route": [{"segment": seg_id}],
        "sources": [{"source": SOURCE_ID, "supports": ["geometry", "name"]}],
        "flags": ["opened_unsourced"],
        "notes": "Its Red and Blue lines are service patterns on the same guideway, drawn as one line. "
                 "No stations yet: Overture's segments carry no stops. Operator as named by the guideway's owner, SFO; to be sourced.",
    }
    out = DATA / "present" / "airtrain"
    note = f"Generated by transit_pipeline.overture from Overture Maps release {OVERTURE_RELEASE}. Don't edit by hand; rerun."
    write_json(out / "lines.json", {"$comment": note, "lines": [line]})
    write_geojson(out / "segments.geojson", [segment], comment=note)
    write_geojson(out / "points.geojson", [], comment=note)
    merge_registry(SOURCES, "sources", SOURCE_ID, [{
        "id": SOURCE_ID,
        "title": f"Overture Maps Foundation, transportation theme, release {OVERTURE_RELEASE}",
        "publisher": "Overture Maps Foundation",
        "url": "https://docs.overturemaps.org/guides/transportation/",
        "type": "dataset",
        "license": "ODbL 1.0: © OpenStreetMap contributors, Overture Maps Foundation",
        "notes": f"Read from s3://{BUCKET}/release/{OVERTURE_RELEASE}/theme=transportation/type=segment/, rail segments in {SFO_BBOX}.",
    }])
    ensure_systems([{"id": "sfo-airtrain", "name": "SFO AirTrain", "short_name": "AirTrain"}])
    print(f"[overture] SFO AirTrain: {len(rows)} segments merged into {len(parts)} parts")


if __name__ == "__main__":
    main()
