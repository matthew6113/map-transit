"""The Bay Area's boundary, where past lines that left the region stop (decision 16).

The nine counties of `src/basemap/region.json`, from Overture Maps' divisions theme (each county's
land and territorial-water areas), joined into one polygon and simplified to about 10 m. It is written
to data/bay-area.geojson, which the past pipeline clips with and the tests read. Read anonymously from
S3 and cached in data/raw/overture/.

    uv run --directory pipeline python -m transit_pipeline.counties register
"""

from __future__ import annotations

import argparse
import json
from functools import cache

import pyarrow.compute as pc
import pyarrow.dataset as ds
import pyarrow.parquet as pq
import shapely
from shapely.geometry import LineString, Point, mapping, shape
from shapely.ops import unary_union

from .common import DATA, ROOT, SOURCES, merge_registry, write_geojson
from .gtfs import to_degrees, to_metres
from .streets import BUCKET, CACHE_DIR, OVERTURE_RELEASE, _filesystem

REGION = json.loads((ROOT / "src" / "basemap" / "region.json").read_text())
OUT = DATA / "bay-area.geojson"
SOURCE_ID = "overture-divisions-2026-09-23-1"
SIMPLIFY_M = 10.0


def _fetch():
    path = CACHE_DIR / "counties.parquet"
    if not path.exists():
        x0, y0, x1, y1 = REGION["maxBounds"]
        dataset = ds.dataset(f"{BUCKET}/release/{OVERTURE_RELEASE}/theme=divisions/type=division_area/",
                             filesystem=_filesystem(), format="parquet")
        filt = ((pc.field("subtype") == "county") & (pc.field("region") == "US-CA")
                & (pc.field("bbox", "xmin") < x1) & (pc.field("bbox", "xmax") > x0)
                & (pc.field("bbox", "ymin") < y1) & (pc.field("bbox", "ymax") > y0))
        table = dataset.to_table(columns=["id", "geometry", "names", "class"], filter=filt)
        path.parent.mkdir(parents=True, exist_ok=True)
        pq.write_table(table, path, compression="zstd")
    return pq.read_table(path).to_pylist()


def build() -> dict:
    """The nine counties joined, in lon/lat, as a GeoJSON feature."""
    wanted = set(REGION["counties"])
    parts = [shapely.from_wkb(r["geometry"]) for r in _fetch() if (r["names"] or {}).get("primary") in wanted]
    found = {(r["names"] or {}).get("primary") for r in _fetch()} & wanted
    if found != wanted:
        raise SystemExit(f"[counties] missing from Overture: {sorted(wanted - found)}")
    region = to_degrees(to_metres(unary_union(parts)).buffer(0).simplify(SIMPLIFY_M))
    region = shapely.set_precision(region, 1e-5)
    return {"comment": (
        "Generated by `python -m transit_pipeline.counties register`; don't edit. The nine Bay Area "
        f"counties of src/basemap/region.json, from Overture Maps {OVERTURE_RELEASE} (divisions, county "
        f"land and territorial-water areas), joined and simplified to about {SIMPLIFY_M:.0f} m. Past "
        "lines that left the region stop at this boundary (decision 16)."),
        "feature": {"type": "Feature", "properties": {"name": "Bay Area (nine counties)", "source": SOURCE_ID},
                    "geometry": mapping(region)}}


@cache
def region():
    """The Bay Area's polygon, in metres."""
    if not OUT.exists():
        raise SystemExit("[counties] data/bay-area.geojson is missing: run `python -m transit_pipeline.counties register`")
    return to_metres(shape(json.loads(OUT.read_text())["features"][0]["geometry"]))


def clip(coords: list[list[float]]) -> tuple[list[list[float]], float]:
    """The longest piece of a line inside the Bay Area, and how much was cut off (metres)."""
    line = to_metres(LineString(coords))
    inside = line.intersection(region())
    pieces = [g for g in getattr(inside, "geoms", [inside]) if isinstance(g, LineString) and not g.is_empty]
    if not pieces:
        raise SystemExit("[counties] the line lies wholly outside the Bay Area")
    keep = max(pieces, key=lambda g: g.length)
    out = [list(c) for c in to_degrees(keep).coords]
    # Keep the line's own direction.
    if line.project(Point(keep.coords[0])) > line.project(Point(keep.coords[-1])):
        out.reverse()
    return out, line.length - keep.length


def register() -> None:
    built = build()
    write_geojson(OUT, [built["feature"]], comment=built["comment"])
    merge_registry(SOURCES, "sources", "overture-divisions-", [{
        "id": SOURCE_ID,
        "title": f"Overture Maps Foundation, divisions theme (county areas), release {OVERTURE_RELEASE}",
        "publisher": "Overture Maps Foundation",
        "url": "https://docs.overturemaps.org/guides/divisions/",
        "type": "dataset",
        "license": "ODbL 1.0: © OpenStreetMap contributors, Overture Maps Foundation",
        "notes": f"County areas (land and territorial water) for {', '.join(REGION['counties'])}, read from "
                 f"s3://{BUCKET}/release/{OVERTURE_RELEASE}/theme=divisions/type=division_area/ and joined into "
                 "data/bay-area.geojson, the boundary where past lines leaving the region stop (decision 16).",
    }])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["register"])
    ap.parse_args()
    register()
    print(f"[counties] {OUT.relative_to(ROOT)}: {region().area / 1e6:.0f} km², {OUT.stat().st_size / 1e3:.0f} KB")


if __name__ == "__main__":
    main()
