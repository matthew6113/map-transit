"""Matthew's review lists, generated from the data: `make checklists`.

Writes docs/checks/present.md: the quotes from scanned PDFs that date today's network, to check
against the page images; its conflicts; and the stretches left undated, with why.

Writes docs/checks/past.md with these lists:
- Page checks (decision 11): every book citation on a record flagged `page_unverified`, with the page
  as given and the facts it supports, so each can be looked up in the book.
- Spot checks (decision 12): every traced past feature, and every one drawn from OpenHistoricalMap,
  with its method, map, estimated error and the review images from `make past-review`.
- Conflicts: every record flagged `conflicting_sources`, with its notes.
- Dates "on or about" (decision 17): every end dated by the month of the order or event that brought
  it, for a newspaper check of the last day.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from .common import DATA, ROOT, SOURCES

OUT = ROOT / "docs" / "checks" / "past.md"
OUT_PRESENT = ROOT / "docs" / "checks" / "present.md"
EXTENSIONS = DATA / "present" / "extensions.json"
REVIEWS = [ROOT / "docs" / "screenshots" / p / "traces" for p in ("p2a", "p2b", "p2c")]  # make past-review, by phase


def records():
    """(kind, folder, properties) for every past line, segment and point."""
    for folder in sorted(p for p in (DATA / "past").glob("*") if p.is_dir()):
        if (folder / "lines.json").exists():
            for line in json.loads((folder / "lines.json").read_text())["lines"]:
                yield "line", folder.name, line
        for file, kind in (("segments.geojson", "segment"), ("points.geojson", "point")):
            if (folder / file).exists():
                for f in json.loads((folder / file).read_text())["features"]:
                    yield kind, folder.name, f["properties"]


def present(sources: dict) -> None:
    """docs/checks/present.md, from data/present/extensions.json."""
    ext = json.loads(EXTENSIONS.read_text()) if EXTENSIONS.exists() else {"systems": {}}
    scanned = {sid for sid, s in sources.items() if "scanned PDF" in s.get("notes", "")}
    lines = ["# Today's network: checks for Matthew", "",
             "Generated by `make checklists` from `data/present/extensions.json`; don't edit by hand.", "",
             "## Quotes from scanned PDFs to check", "",
             "These quotes come from the machine-read text of scanned PDFs. Check each against the page "
             "image, then correct the quote if it differs.", ""]
    quotes, conflicts, undated, announced = [], [], [], []
    for sys_id, sysspec in ext["systems"].items():
        items = [(d["id"], d) for d in sysspec.get("segments", [])]
        items += [(lid, d) for lid, d in sysspec.get("lines", {}).items()]
        items += [(f"{sys_id} station {name}", d) for name, d in sysspec.get("points", {}).items()]
        items += [(sid, d) for sid, d in sysspec.get("dates", {}).items()]
        for rid, d in items:
            for c in d.get("sources", []):
                if c["source"] in scanned:
                    where = f"p. {c['pages']}" if c.get("pages") else "no page given"
                    quotes.append(f"- `{rid}`: {sources[c['source']]['title']}, {where}. {c.get('note', '')}".rstrip())
            if "conflicting_sources" in d.get("flags", []):
                conflicts.append(f"- `{rid}`: {d.get('notes', 'see its sources')}")
            if "opened" in d and d["opened"] is None:
                undated.append(f"- `{rid}` ({d['name']}): {d.get('notes', '')}")
            if "announced" in d.get("notes", "") or any("nnounced" in c.get("note", "") for c in d.get("sources", [])):
                announced.append(f"- `{rid}`: {d.get('opened')}. {d.get('notes', '')}".rstrip())
    lines += (quotes or ["None."]) + ["", "## Conflicting sources", ""] + (conflicts or ["None."])
    lines += ["", "## Dates announced beforehand", "",
              "An agency's own announced date, used with a note (decision of Oct 14). Replace any with a "
              "date confirmed after the fact when one turns up.", ""] + (announced or ["None."])
    lines += ["", "## Stretches left undated", "",
              "Track older than today's service, whose opening isn't sourced yet. The line's own date "
              "shows it on the year slider, lighter.", ""] + (undated or ["None."]) + [""]
    OUT_PRESENT.parent.mkdir(parents=True, exist_ok=True)
    OUT_PRESENT.write_text("\n".join(lines))
    print(f"[checklists] {OUT_PRESENT.relative_to(ROOT)}: {len(quotes)} quotes, {len(conflicts)} conflicts, "
          f"{len(undated)} undated stretches")


def main() -> None:
    sources = {s["id"]: s for s in json.loads(SOURCES.read_text())["sources"]}
    present(sources)
    recs = list(records())

    pages: dict[str, list[str]] = defaultdict(list)
    for kind, folder, p in recs:
        if "page_unverified" not in p.get("flags", []):
            continue
        for c in p["sources"]:
            s = sources.get(c["source"], {})
            if s.get("type") != "book":
                continue
            supports = ", ".join(c.get("supports", []))
            where = f"p. {c['pages']}" if c.get("pages") else "no page given"
            note = f" ({c['note']})" if c.get("note") else ""
            pages[c["source"]].append(f"- {where}: {supports} of {kind} `{p['id']}` ({p.get('name', '')}){note}")

    lines = ["# Past era: checks for Matthew", "",
             "Generated by `make checklists` from `data/past/`; don't edit by hand.", ""]

    lines += ["## Book pages to check (decision 11)", "",
              "Each page below is cited as another work gives it. Check it in the book, then drop the "
              "record's `page_unverified` flag (or correct the date and page).", ""]
    if not pages:
        lines += ["None yet.", ""]
    for sid in sorted(pages):
        s = sources.get(sid, {})
        lines += [f"### {s.get('title', sid)}", ""]
        if s.get("author") or s.get("date"):
            lines += [f"{', '.join(x for x in (s.get('author'), s.get('publisher'), s.get('date')) if x)}.", ""]
        lines += sorted(set(pages[sid])) + [""]

    lines += ["## Traced geometry to spot-check (decision 12)", "",
              "Each traced feature, and each drawn from OpenHistoricalMap, with how it was made. The review "
              "images (`make past-review`) draw it over its map; a corrected trace is drawn twice, as traced "
              "over its own sheet and corrected over the sheet it was corrected against.", "",
              "| Feature | Method | Map | Est. error | Review |", "|---|---|---|---|---|"]
    traced = 0
    for kind, folder, p in recs:
        ohm = "OpenHistoricalMap" in p.get("geometry_method", "")
        if kind == "line" or (p.get("geometry_confidence") == "surveyed" and not ohm):
            continue
        g = p.get("georeference") or {}
        imgs = [f"[{'corrected' if n.stem.endswith('-corrected') else 'as traced' if (d / (p['id'] + '-corrected.jpg')).exists() else 'review'}]"
                f"(../screenshots/{d.parent.name}/traces/{n.name})"
                for d in [next((d for d in reversed(REVIEWS) if (d / f"{p['id']}.jpg").exists()), REVIEWS[0])]
                for n in sorted(d.glob(f"{p['id']}*.jpg")) if n.stem in (p['id'], p['id'] + '-corrected')]  # the latest phase's
        lines.append(f"| `{p['id']}` {p.get('name', '')} | {g.get('method', 'OpenHistoricalMap' if ohm else p.get('geometry_confidence'))} | "
                     f"{g.get('map', '')} | {str(g['est_error_m']) + ' m' if 'est_error_m' in g else ''} | {' '.join(imgs)} |")
        traced += 1
    if not traced:
        lines.append("| None yet | | | | |")
    lines.append("")

    lines += ["## Conflicting sources", ""]
    conflicts = [(k, p) for k, _, p in recs if "conflicting_sources" in p.get("flags", [])]
    if not conflicts:
        lines += ["None yet.", ""]
    for kind, p in conflicts:
        lines.append(f"- {kind} `{p['id']}` ({p.get('name', '')}): {p.get('notes', 'see its sources')}")
    lines.append("")

    lines += ["## Dates \"on or about\" (decision 17)", "",
              "Each end dated by the month of the order or event that brought it, because no source gives the "
              "last day. A newspaper of the time would settle it.", ""]
    about = []
    for kind, _, p in recs:
        if kind != "line":
            continue
        for r in p.get("route", []):
            if "on or about" in (r.get("note") or ""):
                about.append(f"- line `{p['id']}` ({p['name']}) on `{r['segment']}`, to {r.get('to')}: {r['note']}")
        for c in p.get("sources", []):
            if "on or about" in (c.get("note") or "") and "closed" in c.get("supports", []):
                about.append(f"- line `{p['id']}` ({p['name']}), closed {p.get('closed')}: {c['note']}")
    lines += (about or ["None yet."]) + [""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"[checklists] {OUT.relative_to(ROOT)}: {sum(len(v) for v in pages.values())} page checks, "
          f"{traced} traced features, {len(conflicts)} conflicts")


if __name__ == "__main__":
    main()
